-- V1: esquema inicial. Alteracoes posteriores devem entrar em uma nova migration.
CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL CHECK (btrim(nome) <> ''),
    email VARCHAR(254) NOT NULL CHECK (btrim(email) <> ''),
    senha_hash VARCHAR(255) NOT NULL CHECK (btrim(senha_hash) <> ''),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uk_usuarios_email ON usuarios (lower(email));

CREATE TABLE categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL CHECK (btrim(nome) <> ''),
    descricao TEXT,
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE UNIQUE INDEX uk_categorias_nome ON categorias (lower(nome));

CREATE TABLE localizacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    logradouro VARCHAR(200),
    numero VARCHAR(20),
    complemento VARCHAR(150),
    bairro VARCHAR(100),
    cidade VARCHAR(100) NOT NULL CHECK (btrim(cidade) <> ''),
    uf CHAR(2) NOT NULL CHECK (uf ~ '^[A-Z]{2}$'),
    cep VARCHAR(8) CHECK (cep ~ '^[0-9]{8}$'),
    latitude NUMERIC(9,6) CHECK (latitude BETWEEN -90 AND 90),
    longitude NUMERIC(9,6) CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_localizacoes_coordenadas CHECK (
        (latitude IS NULL AND longitude IS NULL)
        OR (latitude IS NOT NULL AND longitude IS NOT NULL)
    )
);

CREATE TABLE ocorrencias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(200) NOT NULL CHECK (btrim(titulo) <> ''),
    descricao TEXT NOT NULL CHECK (btrim(descricao) <> ''),
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    categoria_id BIGINT NOT NULL REFERENCES categorias(id),
    localizacao_id BIGINT NOT NULL REFERENCES localizacoes(id),
    status VARCHAR(30) NOT NULL DEFAULT 'ABERTA',
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_ocorrencias_status CHECK (
        status IN ('ABERTA', 'EM_ANALISE', 'EM_ANDAMENTO', 'RESOLVIDA', 'CANCELADA')
    ),
    CONSTRAINT ck_ocorrencias_datas CHECK (atualizado_em >= criado_em)
);
CREATE INDEX idx_ocorrencias_usuario ON ocorrencias(usuario_id);
CREATE INDEX idx_ocorrencias_categoria ON ocorrencias(categoria_id);
CREATE INDEX idx_ocorrencias_localizacao ON ocorrencias(localizacao_id);
CREATE INDEX idx_ocorrencias_status_criado_em ON ocorrencias(status, criado_em);

CREATE TABLE historico_status (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ocorrencia_id BIGINT NOT NULL REFERENCES ocorrencias(id),
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    status_anterior VARCHAR(30),
    status_novo VARCHAR(30) NOT NULL,
    observacao TEXT,
    alterado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_historico_status_anterior CHECK (
        status_anterior IN ('ABERTA', 'EM_ANALISE', 'EM_ANDAMENTO', 'RESOLVIDA', 'CANCELADA')
    ),
    CONSTRAINT ck_historico_status_novo CHECK (
        status_novo IN ('ABERTA', 'EM_ANALISE', 'EM_ANDAMENTO', 'RESOLVIDA', 'CANCELADA')
    ),
    CONSTRAINT ck_historico_mudanca CHECK (
        status_anterior IS NULL OR status_anterior <> status_novo
    )
);
CREATE INDEX idx_historico_ocorrencia_data ON historico_status(ocorrencia_id, alterado_em);
CREATE INDEX idx_historico_usuario ON historico_status(usuario_id);
